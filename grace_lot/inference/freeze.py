"""Write the validation-selected configuration to ``configs/grace_frozen.toml``.

    python -m grace_lot.inference.freeze [--root results/grace_v2] [--config BASE] [--out FROZEN]

This reads ``<root>/select/selection.json``, applies the chosen overrides
to the base config, and writes every setting out explicitly. The frozen
file is what a later train+val fit and the single test evaluation must use.
Writing it runs nothing on the test actors.
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from grace_lot.config import ROOT, load_config
from grace_lot.inference.run import apply_overrides


def _value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, Path):
        return json.dumps(v.relative_to(ROOT).as_posix())
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{json.dumps(k) if not k.isidentifier() else k} = {_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


def dump_toml(cfg: dict, header: str) -> str:
    lines = [f"# {line}" for line in header.splitlines()] + [""]
    for section, values in cfg.items():
        if section == "selection":
            continue
        lines.append(f"[{section}]")
        lines += [f"{k} = {_value(v)}" for k, v in values.items()]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/grace_v2")
    ap.add_argument("--config")
    ap.add_argument("--out", default=str(ROOT / "configs" / "grace_frozen.toml"))
    ap.add_argument("--tag", help="freeze this validated setting instead of the top-ranked one")
    ap.add_argument("--reason", default="", help="why --tag overrides the top-ranked setting")
    args = ap.parse_args()
    sel = json.loads((Path(args.root) / "select" / "selection.json").read_text())
    best = sel["best"] if not args.tag else next(r for r in sel["rows"] if r["tag"] == args.tag)
    from grace_lot.lot_adapter.program import resolved_lot
    cfg = apply_overrides(load_config(args.config), best["overrides"])
    cfg["lot"] = resolved_lot(cfg["lot"])                     # every semantics setting written out
    cfg["data"]["results_dir"] = (ROOT / args.root / "final").resolve()   # where the train+val fit and test go
    base = args.config or "configs/grace_poc.toml"
    header = (f"FROZEN configuration for GRACE x Embodied-LoT, written {date.today().isoformat()}.\n"
              f"Selected on the validation actors only: setting '{best['tag']}' "
              f"(validation top-1 {best['lot_top1']:.3f}, MRR {best['lot_mrr']:.3f}).\n"
              f"Overrides applied to {base}: {best['overrides']}\n"
              + (f"Chosen by the user over the top-ranked '{sel['best']['tag']}': {args.reason}\n" if args.tag else "")
              + "The test actors have NOT been evaluated. Do not edit this file after the test is run.")
    Path(args.out).write_text(dump_toml(cfg, header), encoding="utf-8")
    load_config(args.out)                       # it must parse back
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
