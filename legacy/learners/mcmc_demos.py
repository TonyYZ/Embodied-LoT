"""Demo for the Metropolis-Hastings learner (``concept_learning``).

Run ``python mcmc_demos.py``. The learner sees graded responses to six
scenes, generated by a hidden TOP detector, and searches graph structure
for a concept that reproduces them.
"""

import sys
from pathlib import Path
sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[2])]   # legacy: siblings + embodied_lot
from concept_learning import ConceptLearner, Observation, evaluate_on_dataset
from dreamcoder_lot import ScannerSpec, build_scanner_graph
from embodied_lot import TRIGRAM_PATTERNS, Orientation
from learning_data import make_trigram_field, predict

SCENES = ["top", "bottom", "center", "universal", "void", "upper"]


def main(iterations=400, seed=0):
    teacher = build_scanner_graph([ScannerSpec("top", TRIGRAM_PATTERNS["top"], Orientation.VERTICAL)])
    data = []
    for name in SCENES:
        scene = make_trigram_field(TRIGRAM_PATTERNS[name])
        data.append(Observation(scene, predict(teacher, Observation(scene, 0.0))[0], label=name))

    best, trace = ConceptLearner(data, n_iterations=iterations, random_seed=seed).run()
    fit = evaluate_on_dataset(best, data)

    print("\n=== MCMC: learn a TOP detector ===")
    print(f"best graph : {best.to_nested_list()}")
    print(f"log-post   : {trace.best_score:+.3f} (iteration {trace.best_iteration}), "
          f"acceptance {trace.acceptance_rate:.2f}")
    print(f"fit        : rmse={fit['rmse']:.3f}  r={fit['correlation']:.3f}")
    for obs, pred in zip(data, fit["predictions"]):
        print(f"  {obs.label:10s} target={obs.response:.3f} pred={pred:.3f}")


if __name__ == "__main__":
    main()
